package repository.db;

import exceptions.RepositoryException;
import model.User;
import repository.UserRepository;
import validators.Validator;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Repository for users stored in the PostgreSQL table {@code users}.
 * Every operation opens its own connection; connections, statements and result sets are closed
 * with try-with-resources. All queries use PreparedStatement parameters, so values are never
 * concatenated into the SQL text. Ids are generated by the database.
 */
public class UserDbRepository extends AbstractDbRepository<Long, User> implements UserRepository {

    private static final String COLUMNS = "id, username, email, password";

    /**
     * @param validator the validator applied to every user before it is saved or updated
     * @param url       the JDBC url of the database (db.url)
     * @param user      the database user (db.user)
     * @param password  the database password (db.password)
     */
    public UserDbRepository(Validator<User> validator, String url, String user, String password) {
        super(validator, url, user, password);
    }

    /**
     * Builds a user from the current row of a result set.
     *
     * @param rs a result set positioned on a row of the users table
     * @return the user described by the row, with its id set
     * @throws SQLException if a column cannot be read
     */
    private User extractUser(ResultSet rs) throws SQLException {
        User user = new User(rs.getString("username"), rs.getString("email"), rs.getString("password"));
        user.setId(rs.getLong("id"));
        return user;
    }

    /**
     * {@inheritDoc}
     *
     * @throws RepositoryException if the database cannot be read
     */
    @Override
    public Optional<User> findOne(Long id) {
        requireNonNull(id, "Id");
        String sql = "SELECT " + COLUMNS + " FROM users WHERE id = ?";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, id);
            try (ResultSet rs = statement.executeQuery()) {
                return rs.next() ? Optional.of(extractUser(rs)) : Optional.empty();
            }
        } catch (SQLException e) {
            throw SqlErrors.wrap("find the user", e);
        }
    }

    /**
     * {@inheritDoc}
     * The users are returned in the order of their ids.
     *
     * @throws RepositoryException if the database cannot be read
     */
    @Override
    public List<User> findAll() {
        String sql = "SELECT " + COLUMNS + " FROM users ORDER BY id";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet rs = statement.executeQuery()) {
            List<User> users = new ArrayList<>();
            while (rs.next()) {
                users.add(extractUser(rs));
            }
            return users;
        } catch (SQLException e) {
            throw SqlErrors.wrap("read the users", e);
        }
    }

    /**
     * Validates the user and inserts it; the id generated by the database is set on the user.
     *
     * @param entity the user to save (its id is ignored, the database generates it)
     * @return the saved user, with the id generated by the database
     * @throws IllegalArgumentException       if {@code entity} is null
     * @throws exceptions.ValidationException if the user is not valid
     * @throws RepositoryException            if the user cannot be saved (e.g. duplicate username or email)
     */
    @Override
    public User save(User entity) {
        requireNonNull(entity, "Entity");
        validator.validate(entity);
        String sql = "INSERT INTO users (username, email, password) VALUES (?, ?, ?)";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, entity.getUsername());
            statement.setString(2, entity.getEmail());
            statement.setString(3, entity.getPassword());
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (keys.next()) {
                    entity.setId(keys.getLong(1));
                }
            }
            return entity;
        } catch (SQLException e) {
            throw SqlErrors.wrap("save the user", e);
        }
    }

    /**
     * {@inheritDoc}
     * The user is read first, so it can be returned after it is deleted.
     * The database also deletes the user's friendships (ON DELETE CASCADE).
     *
     * @throws RepositoryException if the user cannot be deleted
     */
    @Override
    public Optional<User> delete(Long id) {
        requireNonNull(id, "Id");
        Optional<User> existing = findOne(id);
        if (existing.isEmpty()) {
            return existing;
        }
        String sql = "DELETE FROM users WHERE id = ?";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, id);
            statement.executeUpdate();
            return existing;
        } catch (SQLException e) {
            throw SqlErrors.wrap("delete the user", e);
        }
    }

    /**
     * {@inheritDoc}
     * Whether the user exists is decided by the number of rows changed by executeUpdate
     * (0 = no user with this id), without a SELECT first.
     *
     * @throws RepositoryException if the user cannot be updated (e.g. duplicate username or email)
     */
    @Override
    public Optional<User> update(User entity) {
        requireNonNull(entity, "Entity");
        validator.validate(entity);
        if (entity.getId() == null) {
            return Optional.of(entity);
        }
        String sql = "UPDATE users SET username = ?, email = ?, password = ? WHERE id = ?";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, entity.getUsername());
            statement.setString(2, entity.getEmail());
            statement.setString(3, entity.getPassword());
            statement.setLong(4, entity.getId());
            int changedRows = statement.executeUpdate();
            return changedRows == 0 ? Optional.of(entity) : Optional.empty();
        } catch (SQLException e) {
            throw SqlErrors.wrap("update the user", e);
        }
    }

    /**
     * Finds the user with the given username with a single query in the database,
     * instead of the default implementation that filters all users in Java.
     *
     * @param username the username to search for
     * @return the user with this username, or an empty Optional if there is none (also for {@code null})
     * @throws RepositoryException if the database cannot be read
     */
    @Override
    public Optional<User> findByUsername(String username) {
        return findByColumn("username", username);
    }

    /**
     * Finds the user with the given email with a single query in the database,
     * instead of the default implementation that filters all users in Java.
     *
     * @param email the email to search for
     * @return the user with this email, or an empty Optional if there is none (also for {@code null})
     * @throws RepositoryException if the database cannot be read
     */
    @Override
    public Optional<User> findByEmail(String email) {
        return findByColumn("email", email);
    }

    /**
     * Finds the user whose column has the given value.
     *
     * @param column the column to search in; always a fixed name from this class, never user input
     * @param value  the value to look for
     * @return the matching user, or an empty Optional
     * @throws RepositoryException if the database cannot be read
     */
    private Optional<User> findByColumn(String column, String value) {
        if (value == null) {
            return Optional.empty();
        }
        String sql = "SELECT " + COLUMNS + " FROM users WHERE " + column + " = ?";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, value);
            try (ResultSet rs = statement.executeQuery()) {
                return rs.next() ? Optional.of(extractUser(rs)) : Optional.empty();
            }
        } catch (SQLException e) {
            throw SqlErrors.wrap("find the user", e);
        }
    }
}